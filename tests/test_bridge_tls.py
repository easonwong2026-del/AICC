OPENSSL = "/usr/bin/openssl"


def run(*arguments, **keywords):
    return subprocess.run([OPENSSL, *arguments], check=True, capture_output=True, **keywords)


def write_config(path, body):
    path.write_text(body, encoding="utf-8")
    return str(path)


def mint(directory):
    """CA + leaf + identity.json, the layout `bridge_tls` documents."""
    directory = Path(directory)
    ca_config = write_config(directory / "ca.cnf", "\n".join([
        "[req]", "distinguished_name = dn", "prompt = no", "x509_extensions = v3",
        "[dn]", "CN = AICC Test CA", "O = AICC test only",
        "[v3]", "basicConstraints = critical,CA:TRUE", "keyUsage = critical,digitalSignature,keyCertSign",
    ]))
    run("req", "-x509", "-newkey", "rsa:2048", "-nodes", "-sha256", "-days", "2", "-config", ca_config,
        "-keyout", str(directory / "ca.key"), "-out", str(directory / "ca.pem"))
    leaf_config = write_config(directory / "leaf.cnf", "\n".join([
        "[req]", "distinguished_name = dn", "prompt = no",
        "[dn]", "CN = AICC Bridge", "O = AICC test only",
        "[v3]", "basicConstraints = critical,CA:FALSE", "keyUsage = critical,digitalSignature,keyEncipherment",
        "extendedKeyUsage = serverAuth", "subjectAltName = IP:127.0.0.1,DNS:localhost",
    ]))
    run("req", "-new", "-newkey", "rsa:2048", "-nodes", "-sha256", "-config", leaf_config,
        "-keyout", str(directory / "server.key"), "-out", str(directory / "leaf.csr"))
    run("x509", "-req", "-in", str(directory / "leaf.csr"), "-CA", str(directory / "ca.pem"),
        "-CAkey", str(directory / "ca.key"), "-CAcreateserial", "-days", "2", "-sha256",
        "-extfile", leaf_config, "-extensions", "v3", "-out", str(directory / "leaf.pem"))
    (directory / "server.pem").write_text(
        (directory / "leaf.pem").read_text() + (directory / "ca.pem").read_text(), encoding="utf-8")
    os.chmod(directory / "server.key", 0o644)  # the loader must tighten this
    spki = spki_pin(directory / "ca.pem")
    (directory / "identity.json").write_text(json.dumps({
        "spki": spki, "not_after": "2027-11-16T00:00:00Z", "generation": 1,
        "sans": ["127.0.0.1", "localhost"]}), encoding="utf-8")
    return spki


def spki_pin(certificate):
    public = run("x509", "-pubkey", "-noout", "-in", str(certificate)).stdout
    der = run("pkey", "-pubin", "-outform", "DER", input=public).stdout
    return base64.b64encode(hashlib.sha256(der).digest()).decode("ascii")


class TlsMaterialTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.root = Path(self.directory.name)

    def tearDown(self):
        self.directory.cleanup()

    def test_missing_material_means_no_listener(self):
        with self.assertRaises(bridge_tls.TlsUnavailable):
            bridge_tls.load_identity(self.root)

    def test_private_key_permissions_are_tightened_before_use(self):
        mint(self.root)
        self.assertEqual(stat.S_IMODE((self.root / "server.key").stat().st_mode), 0o644)
        material = bridge_tls.load_identity(self.root)
        self.assertEqual(stat.S_IMODE((self.root / "server.key").stat().st_mode), 0o600)
        self.assertEqual(len(material.spki), 44)

    def test_a_truncated_pin_is_refused(self):
        mint(self.root)
        document = json.loads((self.root / "identity.json").read_text())
        document["spki"] = document["spki"][:20]
        (self.root / "identity.json").write_text(json.dumps(document))
        with self.assertRaises(bridge_tls.TlsUnavailable):
            bridge_tls.load_identity(self.root)

    def test_lan_is_not_enabled_by_default(self):
        with patch.dict("os.environ", {}, clear=True):
            self.assertEqual(server.lan_bootstrap(), (None, None))
            self.assertIsNone(server._lan_info)

    def test_certificates_absent_fails_closed(self):
        with patch.dict("os.environ", {"EINK_HOST": "0.0.0.0", "EINK_CERT_DIR": str(self.root)}, clear=True):
            self.assertEqual(server.lan_bootstrap(), (None, None), "no silent plaintext fallback")
        self.assertIsNone(server._lan_info)
        self.assertFalse(server.server_identity()["lan_serving"])


class LanListenerTests(unittest.TestCase):
    """A real HTTPS listener on an ephemeral port, exercised like a device would."""

    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.root = Path(self.directory.name)
        self.spki = mint(self.root)
        material = bridge_tls.load_identity(self.root)
        context = bridge_tls.build_context(material)
        self.server = server.LanServer(("127.0.0.1", 0), server.LanHandler)
        self.server.socket = context.wrap_socket(self.server.socket, server_side=True)
        self.port = self.server.server_address[1]
        self.worker = threading.Thread(target=self.server.serve_forever, daemon=True)
        self.worker.start()
        self.token = server._token
        server._rates.clear()
        server._pair_failures.clear()
        server._pair_code = None
        server._snapshot = None
        self.data = patch.object(server, "DATA_PATH", self.root / "status.json")
        self.data.start()

    def tearDown(self):
        self.server.shutdown()
        self.server.server_close()
        self.worker.join()
        self.data.stop()
        self.directory.cleanup()

    def client(self, *, pin=None, verify=True, hostname="localhost"):
        # A device pins the trust anchor it was given, then lets the TLS stack
        # prove the presented leaf chains to it.  A pin that does not match the
        # anchor means "this is not the Mac I paired with" — refuse before
        # sending a code or a token.
        if pin is not None and pin != spki_pin(self.root / "ca.pem"):
            raise ssl.SSLError("certificate pin mismatch")
        context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
        if verify:
            context.load_verify_locations(str(self.root / "ca.pem"))
            context.check_hostname = True
        else:
            context.check_hostname = False
            context.verify_mode = ssl.CERT_NONE
        raw = socket.create_connection(("127.0.0.1", self.port), timeout=5)
        return context.wrap_socket(raw, server_hostname=hostname)

    def request(self, method, path, *, token=None, body=None, **client_options):
        connection = http.client.HTTPConnection("127.0.0.1", self.port, timeout=5)
        connection.sock = self.client(**client_options)
        try:
            headers = {"Host": "localhost", "Connection": "close"}
            if token:
                headers["Authorization"] = "Bearer " + token
            if body is not None:
                headers["Content-Type"] = "application/json"
            connection.request(method, path, body=body, headers=headers)
            response = connection.getresponse()
            return response.status, response.read()
        finally:
            connection.close()

    def test_negotiates_tls13_and_still_accepts_tls12(self):
        connection = self.client()
        try:
            self.assertEqual(connection.version(), "TLSv1.3")
        finally:
            connection.close()
        legacy = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
        legacy.load_verify_locations(str(self.root / "ca.pem"))
        legacy.minimum_version = ssl.TLSVersion.TLSv1_2
        legacy.maximum_version = ssl.TLSVersion.TLSv1_2
        raw = socket.create_connection(("127.0.0.1", self.port), timeout=5)
        with legacy.wrap_socket(raw, server_hostname="localhost") as tls:
            self.assertEqual(tls.version(), "TLSv1.2")

    def test_tls10_is_refused(self):
        context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
        context.check_hostname = False
        context.verify_mode = ssl.CERT_NONE
        with self.assertWarns(DeprecationWarning):
            context.minimum_version = ssl.TLSVersion.TLSv1
            context.maximum_version = ssl.TLSVersion.TLSv1
        raw = socket.create_connection(("127.0.0.1", self.port), timeout=5)
        with self.assertRaises(ssl.SSLError):
            context.wrap_socket(raw, server_hostname="localhost")

    def test_unknown_ca_and_wrong_hostname_are_refused(self):
        stranger = Path(self.directory.name) / "stranger"
        stranger.mkdir()
        mint(stranger)
        with self.assertRaises(ssl.SSLCertVerificationError):
            self.request("GET", "/api/health/live", verify=True, hostname="wrong.example")
        context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
        context.load_verify_locations(str(stranger / "ca.pem"))
        raw = socket.create_connection(("127.0.0.1", self.port), timeout=5)
        with self.assertRaises(ssl.SSLCertVerificationError):
            context.wrap_socket(raw, server_hostname="localhost")

    def test_health_is_readable_but_status_needs_the_token(self):
        status, body = self.request("GET", "/api/health/live")
        self.assertEqual(status, 200)
        self.assertEqual(json.loads(body)["protocol"], "aicc")
        status, _ = self.request("GET", "/api/status")
        self.assertEqual(status, 401)
        status, body = self.request("GET", "/api/status", token=self.token)
        self.assertEqual(status, 200)
        self.assertGreaterEqual(json.loads(body)["schema_version"], 3)

    def test_management_routes_are_not_reachable_over_lan(self):
        for method, path in (("GET", "/api/health/ready"), ("POST", "/api/pairing"),
                             ("POST", "/api/shutdown"), ("GET", "/api/accounts"),
                             ("POST", "/api/magpie/refresh")):
            status, _ = self.request(method, path, token=self.token, body="{}")
            self.assertEqual(status, 403, f"{method} {path} must not be exposed to the network")

    def test_plain_http_on_the_lan_port_is_rejected(self):
        raw = socket.create_connection(("127.0.0.1", self.port), timeout=5)
        try:
            raw.sendall(b"GET /api/status HTTP/1.1\r\nHost: localhost\r\n\r\n")
            with self.assertRaises((ssl.SSLError, ConnectionResetError, socket.timeout, OSError)):
                raw.recv(64)
        finally:
            raw.close()

    def test_pinning_accepts_the_real_identity_and_rejects_a_foreign_one(self):
        status, _ = self.request("GET", "/api/status", token=self.token, pin=self.spki)
        self.assertEqual(status, 200)
        stranger = Path(self.directory.name) / "stranger"
        stranger.mkdir()
        foreign = mint(stranger)
        self.assertNotEqual(foreign, self.spki)
        with self.assertRaises(ssl.SSLError):
            self.request("GET", "/api/status", token=self.token, pin=foreign)

    def test_pairing_over_https_returns_the_token(self):
        server._pair_code = None
        with server._lock:
            server._pair_code = "12345678"
            server._pair_deadline = __import__("time").monotonic() + 60
        status, body = self.request("POST", "/api/pair", body=json.dumps({"code": "12345678"}))
        self.assertEqual(status, 200)
        self.assertEqual(json.loads(body)["token"], self.token)

    def test_wrong_code_is_counted_per_address(self):
        import time
        with server._lock:
            server._pair_code = "87654321"
            server._pair_deadline = time.monotonic() + 60
        for _ in range(server.PAIR_FAILURES_PER_WINDOW):
            status, _ = self.request("POST", "/api/pair", body=json.dumps({"code": "00000000"}))
            self.assertEqual(status, 403)
        status, _ = self.request("POST", "/api/pair", body=json.dumps({"code": "87654321"}))
        self.assertEqual(status, 429, "the correct code must not be usable after the limit")


def spki_of_peer(connection, root):
    """Pin check the way a device does it: over the presented chain, not a file."""
    der = connection.getpeercert(binary_form=True)
    pem = ssl.DER_cert_to_PEM_cert(der)
    leaf = Path(root) / "peer.pem"
    leaf.write_text(pem, encoding="utf-8")
    return spki_pin(leaf)


class DiscoveryPayloadTests(unittest.TestCase):
    def test_broadcast_carries_the_pin_but_never_a_token(self):
        with patch.dict("os.environ", {"EINK_HOST": "0.0.0.0"}, clear=True):
            payload = server.server_identity()
            self.assertEqual(payload["bind"], "lan")
            self.assertEqual(payload["protocol_version"], bridge_tls.PROTOCOL_VERSION)
            self.assertNotIn("token", json.dumps(payload))
            self.assertFalse(payload["lan_serving"], "identity must not claim TLS it does not have")


