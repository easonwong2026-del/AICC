"""PR-B: the LAN side must be HTTPS with a pinned identity, or nothing at all.

These tests mint throwaway certificates with the system `openssl` (test data
only — the shipped key is generated by the Rust worker with `rcgen`), then put
them through the same code path the product uses.
"""

